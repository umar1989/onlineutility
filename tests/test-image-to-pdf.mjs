import { chromium } from 'playwright';
import { serve } from './serve.mjs';
import fs from 'node:fs';
import { PDFDocument } from 'pdf-lib';
const s = await serve(4399);
const b = await chromium.launch(); const p = await b.newPage();
const errors = []; p.on('pageerror', (e) => errors.push(e.message)); p.on('console', (m) => m.type() === 'error' && errors.push(m.text()));
await p.goto('http://localhost:4399/image-to-pdf/');
await p.setInputFiles('#ip-file', ['tests/fixtures/photo.jpg', 'tests/fixtures/photo.png']);
console.log('items', await p.locator('#ip-list li').count());
await p.click('#ip-list li:nth-child(2) [data-act=up]');
console.log('first now:', await p.textContent('#ip-list li:first-child span'));
await p.click('#ip-go');
await p.waitForFunction(() => !document.querySelector('#ip-result').hidden, null, { timeout: 30000 });
console.log(await p.textContent('#ip-out'));
const [dl] = await Promise.all([p.waitForEvent('download'), p.click('#ip-dl')]);
await dl.saveAs('tests/fixtures/img.pdf');
const d = await PDFDocument.load(fs.readFileSync('tests/fixtures/img.pdf'));
console.log('pages', d.getPageCount(), d.getPage(0).getSize());
console.log('errors', errors); await b.close(); s.close();
