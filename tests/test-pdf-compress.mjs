import { chromium } from 'playwright';
import { serve } from './serve.mjs';
import fs from 'node:fs';
import { PDFDocument } from 'pdf-lib';
const s = await serve(4399);
const b = await chromium.launch();
const p = await b.newPage();
const errors = [];
p.on('pageerror', (e) => errors.push(e.message));
p.on('console', (m) => m.type() === 'error' && errors.push(m.text()));
await p.goto('http://localhost:4399/compress-pdf-to-specific-size/');
await p.setInputFiles('#pc-file', 'tests/fixtures/sample.pdf');
await p.fill('#pc-size', '200'); await p.selectOption('#pc-unit', 'KB');
await p.click('#pc-go');
await p.waitForFunction(() => !document.querySelector('#pc-result').hidden, null, { timeout: 90000 });
console.log(await p.textContent('#pc-out'));
const [dl] = await Promise.all([p.waitForEvent('download'), p.click('#pc-dl')]);
await dl.saveAs('tests/fixtures/out.pdf');
const d = await PDFDocument.load(fs.readFileSync('tests/fixtures/out.pdf'));
console.log('out pages', d.getPageCount(), 'bytes', fs.statSync('tests/fixtures/out.pdf').size);
console.log('errors', errors);
await b.close(); s.close();
